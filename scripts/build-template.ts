// Writes switch/payday-room.template.yaml: the source template with each
// agent's instructions filled in from its AGENT.md, so the file you import
// into Switch Console is self-contained.
//
//   node scripts/build-template.ts
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseDocument } from "yaml";
import { ROOT } from "./lib.ts";

const src = join(ROOT, "switch", "payday-room.src.yaml");
const out = join(ROOT, "switch", "payday-room.template.yaml");
const doc = parseDocument(readFileSync(src, "utf8"));

const agents = doc.get("agents") as { items: { get: (k: string) => unknown; set: (k: string, v: unknown) => void }[] };
for (const agent of agents.items) {
  const name = String(agent.get("name"));
  agent.set("instructions", readFileSync(join(ROOT, "switch", `${name}.AGENT.md`), "utf8"));
}

const header = "# GENERATED by `node scripts/build-template.ts` from payday-room.src.yaml and the *.AGENT.md files. Import this one.\n";
writeFileSync(out, header + doc.toString({ lineWidth: 0 }));
console.log(`wrote ${out}`);
